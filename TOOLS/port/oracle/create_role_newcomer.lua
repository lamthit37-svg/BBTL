-- Script gọi math.random cho bộ đồ tân thủ (lúc nạp và mỗi lần đổi giới) và cho nút ngẫu nhiên (tóc,
-- mặt, bộ đồ): kịch bản đưa sẵn dãy số theo đúng thứ tự gọi, test của bản port đưa cùng dãy đó.
-- Thứ tự: lúc nạp 1; mở bảng (chọn nữ) 2; chọn nam 0; nút ngẫu nhiên: tóc 2, mặt 1, bộ đồ 1; xem
-- trước nữ 1; mở lại bảng 0.
__rolls = { 1, 2, 0, 2, 1, 1, 1, 0 }
function math.random(low, high)
    local value = table.remove(__rolls, 1)
    if value == nil then error("kịch bản hết số ngẫu nhiên", 2) end
    if value < low or value > high then
        error("số ngẫu nhiên " .. tostring(value) .. " ngoài " .. tostring(low) .. ".." .. tostring(high), 2)
    end
    return value
end
