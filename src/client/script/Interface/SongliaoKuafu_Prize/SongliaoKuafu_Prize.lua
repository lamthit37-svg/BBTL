function SongliaoKuafu_Prize_PreLoad()
    this:RegisterEvent("TSL_SHOWAWARD", true)
	this:RegisterEvent("HIDE_ON_SCENE_TRANSED", true)
	this:RegisterEvent("VIEW_RESOLUTION_CHANGED",false)     -- 窗口分辨率发生变化
    this:RegisterEvent("ADJEST_UI_POS",false)               -- 窗口尺寸发生变化
end -- end func SongliaoKuafu_Prize_PreLoad()

function SongliaoKuafu_Prize_OnLoad()
    SongliaoKuafu_Prize_UnifiedPosition = SongliaoKuafu_Prize_Frame:GetProperty("UnifiedPosition")
    SongliaoKuafu_Prize_InitCtrlList()
end -- end func SongliaoKuafu_Prize_OnLoad()

function SongliaoKuafu_Prize_OnEvent(event)
    if (event == "TSL_SHOWAWARD") then
        SongliaoKuafu_Prize_Show()
        SongliaoKuafu_Prize_ShowAwardList()
    elseif (event == "HIDE_ON_SCENE_TRANSED") then
        SongliaoKuafu_Prize_Hide()
    elseif (event == "VIEW_RESOLUTION_CHANGED") then
        SongliaoKuafu_Prize_UnifiedPos()
    elseif (event == "ADJEST_UI_POS") then
        SongliaoKuafu_Prize_UnifiedPos()
    end
end -- end func SongliaoKuafu_Prize_OnEvent()

-- 界面默认位置
