-- 刷新奖励物品
function SongliaoKuafu_Prize_ShowAwardList()
    -- 如果展示控件列表没有初始化 就初始换一下
    if (SongliaoKuafu_Prize_CtrlList_Win == nil or SongliaoKuafu_Prize_CtrlList_Lose == nil) then
        SongliaoKuafu_Prize_InitCtrlList()
    end

    local levelStage = SongliaoKuafu_Prize_GetLevelStage() + 1
    if (levelStage < 1) then
        return
    end

	local AwardInfoList = nil
	if (Player:GetData("IsOriginalJD") == 1) then
		AwardInfoList = SongliaoKuafu_Prize_AwardList_Ori
	elseif (Player:GetData("Is2606S") == 1) then
		AwardInfoList = SongliaoKuafu_Prize_AwardList_QX
	else
		AwardInfoList = SongliaoKuafu_Prize_AwardList
	end
	if (AwardInfoList == nil) then
		return
	end
    -- 胜利方
    for i=1, table.getn(SongliaoKuafu_Prize_CtrlList_Win), 1 do
        for j=1, table.getn(SongliaoKuafu_Prize_CtrlList_Win[i]), 1 do
            if (AwardInfoList.Win[i][levelStage] ~= nil) then
                local award = AwardInfoList.Win[i][levelStage][j]
                if (award ~= nil) then
                    if (SongliaoKuafu_Prize_CtrlList_Win[i][j] ~= nil) then
                        local theAction = DataPool:CreateActionItemForShow(award.id, 1)
						SongliaoKuafu_Prize_CtrlList_Win[i][j].showCtrl:SetActionItem(theAction:GetID())
						local numText = ScriptGlobal_Format("#{SLDZ_220216_130}", award.num)
                        SongliaoKuafu_Prize_CtrlList_Win[i][j].showNum:SetText(numText)
                        SongliaoKuafu_Prize_CtrlList_Win[i][j].showCtrl:Show()
                    end
                else
                    SongliaoKuafu_Prize_CtrlList_Win[i][j].showCtrl:Hide()
                end
            end
        end -- end for
    end -- end for

    -- 失败方
    for i=1, table.getn(SongliaoKuafu_Prize_CtrlList_Lose), 1 do
        for j=1, table.getn(SongliaoKuafu_Prize_CtrlList_Lose[i]), 1 do
            if (AwardInfoList.Lose[i][levelStage] ~= nil) then
                local award = AwardInfoList.Lose[i][levelStage][j]
                if (award ~= nil) then
                    if (SongliaoKuafu_Prize_CtrlList_Lose[i][j] ~= nil) then
                        local theAction = DataPool:CreateActionItemForShow(award.id, 1)
						SongliaoKuafu_Prize_CtrlList_Lose[i][j].showCtrl:SetActionItem(theAction:GetID())
						local numText = ScriptGlobal_Format("#{SLDZ_220216_130}", award.num)
                        SongliaoKuafu_Prize_CtrlList_Lose[i][j].showNum:SetText(numText)
                        SongliaoKuafu_Prize_CtrlList_Lose[i][j].showCtrl:Show()
                    end
                else
                    SongliaoKuafu_Prize_CtrlList_Lose[i][j].showCtrl:Hide()
                end
            end
        end -- end for
    end -- end for
end -- end func SongliaoKuafu_Prize_ShowAwardList()

-- 获取等级段
function SongliaoKuafu_Prize_GetLevelStage()
    local level = Player:GetLevel()

    if (level >= 60 and level <= 69) then
		return SongliaoKuafu_Prize_LevelStage.Stage60
	elseif (level >= 70 and level <= 79) then
        return SongliaoKuafu_Prize_LevelStage.Stage70
    elseif (level >= 80 and level <= 89) then
        return SongliaoKuafu_Prize_LevelStage.Stage80
    elseif (level >= 90 and level <= 109) then
        return SongliaoKuafu_Prize_LevelStage.Stage90
    elseif (level >= 110 and level <= 119) then
		return SongliaoKuafu_Prize_LevelStage.Stage110
	elseif (level >= 120) then
		return SongliaoKuafu_Prize_LevelStage.Stage120
    end

    return SongliaoKuafu_Prize_LevelStage.StageError
end -- end func SongliaoKuafu_Prize_GetLevelStage()