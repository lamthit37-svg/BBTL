                    end
                else
                    CampPVP2023_Prize_CtrlList_FlagDaiBi[i][j].showCtrl:Hide()
                end
            end
        end -- end for
    end -- end for
	local myCamp = ZYPVP_RankList:Lua_ZYPVPVGetMyCamp()
    -- 胜利方
    for i=1, table.getn(CampPVP2023_Prize_CtrlList_Win), 1 do
        for j=1, table.getn(CampPVP2023_Prize_CtrlList_Win[i]), 1 do
            if (nTable.Win[i][levelStage] ~= nil) then
                local award = nTable.Win[i][levelStage][j]
                if (award ~= nil) then
                    if (CampPVP2023_Prize_CtrlList_Win[i][j] ~= nil) then
						if i == 1 and j == 1 then
							if myCamp == 1 then
