function CampPVP2023_Prize_OnLoad()
    CampPVP2023_Prize_UnifiedPosition = CampPVP2023_Prize_Frame:GetProperty("UnifiedPosition")
    CampPVP2023_Prize_InitCtrlList()
end -- end func CampPVP2023_Prize_OnLoad()

function CampPVP2023_Prize_OnEvent(event)
    if (event == "ZYPVP_SHOW_AWARD") then
        CampPVP2023_Prize_Show()
        CampPVP2023_Prize_ShowAwardList()
    elseif (event == "HIDE_ON_SCENE_TRANSED") then
        CampPVP2023_Prize_Hide()
    elseif (event == "VIEW_RESOLUTION_CHANGED") then
        CampPVP2023_Prize_UnifiedPos()
    elseif (event == "ADJEST_UI_POS") then
        CampPVP2023_Prize_UnifiedPos()
    end
end -- end func CampPVP2023_Prize_OnEvent()

