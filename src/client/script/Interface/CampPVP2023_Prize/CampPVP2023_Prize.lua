    if (CampPVP2023_Prize_CtrlList_Win == nil or CampPVP2023_Prize_CtrlList_Lose == nil or CampPVP2023_Prize_CtrlList_DaiBi == nil or CampPVP2023_Prize_CtrlList_FlagDaiBi == nil) then
        CampPVP2023_Prize_InitCtrlList()
    end

    local levelStage = CampPVP2023_Prize_GetLevelStage() + 1
    if (levelStage < 1) then
        return
    end
	local nTable = {}
	if 1 == Player:GetData("IsOriginalJD") then
		nTable = CampPVP2023_Prize_AwardList
	else
		nTable = CampPVP2023_Prize_AwardList
	end
	
	if 1 == Player:GetData("Is2606S") then
		nTable = CampPVP2023_Prize_AwardList2
	end
	
	-- 代币
    for i=1, table.getn(CampPVP2023_Prize_CtrlList_DaiBi), 1 do
        for j=1, table.getn(CampPVP2023_Prize_CtrlList_DaiBi[i]), 1 do
            if (nTable.DaiBi[i][levelStage] ~= nil) then
                local award = nTable.DaiBi[i][levelStage][j]
                if (award ~= nil) then
                    if (CampPVP2023_Prize_CtrlList_DaiBi[i][j] ~= nil) then
                        local theAction = DataPool:CreateActionItemForShow(award.id, 1)
						CampPVP2023_Prize_CtrlList_DaiBi[i][j].showCtrl:SetActionItem(theAction:GetID())
						local numText = ScriptGlobal_Format("#{SLDZ_220216_130}", award.num)
                        CampPVP2023_Prize_CtrlList_DaiBi[i][j].showNum:SetText(numText)
                        CampPVP2023_Prize_CtrlList_DaiBi[i][j].showCtrl:Show()
                    end
                else
                    CampPVP2023_Prize_CtrlList_DaiBi[i][j].showCtrl:Hide()
                end
            end
        end -- end for
    end -- end for
	
	-- 旗帜代币
    for i=1, table.getn(CampPVP2023_Prize_CtrlList_FlagDaiBi), 1 do
