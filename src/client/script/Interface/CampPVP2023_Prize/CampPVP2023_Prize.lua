-- 获取等级段
function CampPVP2023_Prize_GetLevelStage()
    local level = Player:GetLevel()

    if (level >= 60 and level <= 69) then
		return CampPVP2023_Prize_LevelStage.Stage60
	elseif (level >= 70 and level <= 79) then
        return CampPVP2023_Prize_LevelStage.Stage70
    elseif (level >= 80 and level <= 89) then
        return CampPVP2023_Prize_LevelStage.Stage80
    elseif (level >= 90 and level <= 109) then
        return CampPVP2023_Prize_LevelStage.Stage90
    elseif (level >= 110 and level <= 119) then
        return CampPVP2023_Prize_LevelStage.Stage110
	 elseif (level >= 120) then
        return CampPVP2023_Prize_LevelStage.Stage120
    end

    return CampPVP2023_Prize_LevelStage.StageError
end -- end func CampPVP2023_Prize_GetLevelStage()