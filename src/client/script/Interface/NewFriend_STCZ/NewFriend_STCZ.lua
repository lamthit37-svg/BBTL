--更新领奖按钮状态Tips
function NewFriend_STCZ_Update_PrizeBtn(nGrade)
	if nGrade <= 1 or nGrade > 9 then
		return
	end
	
	--if g_NewFriend_STCZ_PrizeDataMD <= 0 then
	--	return
	--end
	
	local strOldMasterName = GetMasterName()
	local nMasterGrade = 0
	if g_NewFriend_STCZ_BaishiBeginLevel < 10 then
		nMasterGrade = 0
	else
		--nMasterGrade = math.floor(g_NewFriend_STCZ_BaishiBeginLevel/10)
		if g_NewFriend_STCZ_BaishiBeginLevel <= 39 then
			nMasterGrade = 2
		elseif g_NewFriend_STCZ_BaishiBeginLevel > 39 and g_NewFriend_STCZ_BaishiBeginLevel <= 49 then
			nMasterGrade = 5
		elseif g_NewFriend_STCZ_BaishiBeginLevel > 49 and g_NewFriend_STCZ_BaishiBeginLevel <= 59 then
			nMasterGrade = 6
		elseif g_NewFriend_STCZ_BaishiBeginLevel > 59 and g_NewFriend_STCZ_BaishiBeginLevel <= 69 then
			nMasterGrade = 7
		elseif g_NewFriend_STCZ_BaishiBeginLevel > 69 and g_NewFriend_STCZ_BaishiBeginLevel <= 79 then
			nMasterGrade = 8
		elseif g_NewFriend_STCZ_BaishiBeginLevel > 79 and g_NewFriend_STCZ_BaishiBeginLevel <= 89 then
			nMasterGrade = 9
		elseif g_NewFriend_STCZ_BaishiBeginLevel >= 89 then
			nMasterGrade = 10
		end
	end
	
	if nMasterGrade > 10 then
		nMasterGrade = 9
	end
	local nGradeMD = 0
	for i=1, 4 do
		if nGrade > 8 and nGrade <= 10 then
			nGradeMD = nGrade - 8
		else
			nGradeMD = nGrade
		end
		local nBtnIndex = (nGradeMD - 1)*4 + i
		local nBtnTips = Lua_GetDataByBinary(g_NewFriend_STCZ_PrizeDataMD, nBtnIndex - 1)
		if nBtnTips == 1 then
			NewFriend_STCZ_PrizeUpdate(i)
		else
			--PushDebugMessage( tostring(g_NewFriend_STCZ_BaishiBeginLevel) )
			if ((strOldMasterName == "" and nMasterGrade == 0) or (nGrade < nMasterGrade)) then
				NewFriend_STCZ_NoActiveUpdate(i)
			elseif NewFriend_STCZ_BtnStatus(nGrade, i) ~= 1 then
				NewFriend_STCZ_NoPrizeUpdate(i)
			end
		end
	end
end

