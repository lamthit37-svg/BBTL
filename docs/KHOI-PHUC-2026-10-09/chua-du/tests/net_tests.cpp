[[nodiscard]] bool wait_ready(SocketHandle socket, bool write, Milliseconds limit) {
    PollSet poll;
    PollEvents events;
    if (!poll.add(socket, 1)) return false;
    poll.want_write(1, write);
    return poll.wait(limit, events).has_value() && !events.empty();
}

